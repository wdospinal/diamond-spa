type Pillar = { icon: string; title: string; body: string }
type BilingualPillar = { icon: string; en: { title: string; body: string }; es: { title: string; body: string } }

function mapPillars(items: BilingualPillar[], locale: 'en' | 'es'): Pillar[] {
  return items.map(({ icon, en, es }) => ({ icon, ...(locale === 'en' ? en : es) }))
}

type Therapist = { name: string; role: string; years: string; specialty: string }
type BilingualTherapist = {
  /**
   * Clave estable para analitica. El nombre es texto de pantalla: si alguien
   * lo corrige, la metrica de esa terapeuta se partiria en dos. El id no cambia.
   */
  id: string
  name: string
  en: { role: string; years: string; specialty: string }
  es: { role: string; years: string; specialty: string }
}

function mapTherapists(items: BilingualTherapist[], locale: 'en' | 'es'): Therapist[] {
  return items.map(({ name, en, es }) => ({ name, ...(locale === 'en' ? en : es) }))
}

